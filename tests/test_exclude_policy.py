def test_default_exclude_policy_contains_expected_names():
    """The built-in default must cover the obvious never-walk dirs.

    These are the names the user explicitly named when proposing the
    feature. Any future addition is welcome but these MUST be present.
    """
    from config import DEFAULT_EXCLUDE_POLICY

    must_contain = {
        '.git', '.venv', 'venv',
        'node_modules', '__pycache__',
        'dist', 'build',
        'target',  # JVM/Scala/Rust
        '.idea', '.vscode',
        '.mypy_cache', '.pytest_cache', '.ruff_cache',
    }
    missing = must_contain - set(DEFAULT_EXCLUDE_POLICY)
    assert not missing, (
        f'DEFAULT_EXCLUDE_POLICY is missing expected names: {sorted(missing)}'
    )


def test_default_policy_covers_all_supported_languages():
    """For every language/tool Ariadne indexes, the policy excludes the
    canonical autogenerated and cache directories that ecosystem produces.

    Driven by the CATALOG_EXTS list (each extension is paired below with
    the build/cache dirs that ecosystem creates). When a new language
    lands in CATALOG_EXTS, add its build artifacts to the table below
    AND to DEFAULT_EXCLUDE_POLICY. This test fails the moment the policy
    drifts from the supported-language matrix.
    """
    from config import DEFAULT_EXCLUDE_POLICY

    expected_by_ecosystem: dict[str, set[str]] = {
        # Python (.py) — interpreter/test/typecheck caches + venvs
        'python': {
            '__pycache__', '.venv', 'venv', 'env',
            '.pytest_cache', '.mypy_cache', '.ruff_cache',
            '.tox', '.nox', '.hypothesis',
            'site-packages', '.eggs',
        },
        # JavaScript / TypeScript (.js / .jsx / .ts / .tsx / .mjs)
        # Package managers + framework dev caches + vendored ESM bundles.
        'javascript_typescript': {
            'node_modules', 'web_modules',
            'bower_components', 'jspm_packages',
            '.next', '.nuxt', '.svelte-kit',
            '.cache', '.parcel-cache', '.turbo',
            '.vite', '.angular',
            '.docusaurus', '.umi', 'storybook-static',
            '__generated__',
        },
        # JS / TS deploy / hosting platform caches
        'js_deploy_caches': {
            '.vercel', '.netlify',
        },
        # Scala / Java (.scala / .sbt / .java) — JVM build tooling
        'scala_java': {
            'target', '.gradle', '.bsp', '.metals', '.bloop',
            '.scala-build',
        },
        # Test / coverage output (cross-language)
        'test_coverage': {
            'coverage', 'htmlcov', '.coverage',
        },
        # Infra-as-code build caches that show up in monorepos and that
        # we never want indexed (binary plan files, downloaded providers).
        'iac_cloud': {
            '.terraform', '.pulumi', '.serverless', '.aws-sam',
            '.firebase', '.cdk.out',
        },
        # Generic build output (matches every compiled language)
        'generic_build': {
            'build', 'dist', 'out',
        },
        # IDE / editor metadata
        'ide': {
            '.idea', '.vscode', '.vs', '.fleet',
        },
        # Generated docs / static sites
        'generated_docs': {
            '_site', 'generated-docs',
        },
        # VCS metadata (HOCON / config / everything)
        'vcs': {
            '.git', '.hg', '.svn',
        },
        # Vendored deps (Go modules vendor dir, PHP composer vendor, etc.)
        'vendor': {
            'vendor',
        },
    }

    policy = set(DEFAULT_EXCLUDE_POLICY)
    failures: list[str] = []
    for ecosystem, names in expected_by_ecosystem.items():
        missing = names - policy
        if missing:
            failures.append(
                f"{ecosystem}: missing {sorted(missing)}"
            )

    assert not failures, (
        'DEFAULT_EXCLUDE_POLICY is missing autogenerated-content '
        'entries for one or more supported ecosystems:\n  '
        + '\n  '.join(failures)
    )


