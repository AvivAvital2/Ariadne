def test_resolve_excluded_dirs_idempotent_for_duplicate_name(tmp_path):
    """A name appearing in both ``exclude_policy`` and per-source
    ``exclude_dirs`` is silently deduplicated — no error, no warning,
    and no double-counting in the resolved set."""
    from config import Config

    yaml_path = tmp_path / 'ariadne.yaml'
    yaml_path.write_text(
        'exclude_policy:\n'
        '  - .git\n'
        '  - node_modules\n'
        'sources:\n'
        '  myapp:\n'
        '    path: /tmp/myapp\n'
        '    exclude_dirs:\n'
        '      - node_modules\n'
        '      - charts\n',
        encoding='utf-8',
    )
    cfg = Config(config_path=yaml_path)
    resolved = list(cfg.resolve_excluded_dirs('myapp'))
    # Sorted result should not duplicate node_modules
    assert resolved.count('node_modules') == 1
    assert set(resolved) == {'.git', 'node_modules', 'charts'}


