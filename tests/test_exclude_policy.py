"""Tests for the exclude policy / exempt_dirs design.

This file covers the consolidation work that replaces:
  - ``docgen.staleness._EXCLUDED_DIRS``  (private hardcoded list)
  - ``docgen.catalog_writer._SKIP_DIR_NAMES``  (private hardcoded list)

with a single canonical default in ``config.py`` (``DEFAULT_EXCLUDE_POLICY``),
optionally overridable at the top level of ``ariadne.yaml`` via
``exclude_policy:``, plus a per-source ``exempt_dirs:`` field that
*subtracts* from the effective set.

The effective excluded-dir set per source is:

    (config.exclude_policy ∪ source.exclude_dirs) − source.exempt_dirs

Behavior contracts asserted here:

  * Built-in default is comprehensive (includes the obvious never-walk
    names: ``.git``, ``node_modules``, ``__pycache__``, ``.venv``,
    ``dist``, ``target``, ...).
  * ``exclude_policy:`` in ``ariadne.yaml`` REPLACES the default — empty
    tuple means a full walk.
  * Per-source ``exclude_dirs:`` UNIONS with the policy.
  * Per-source ``exempt_dirs:`` SUBTRACTS from the union (rare opt-out
    for projects that legitimately have a ``dist/`` worth indexing).
  * Duplicate names between ``exclude_policy`` and per-source
    ``exclude_dirs`` are silently deduplicated (idempotent).
  * Overlap between per-source ``exclude_dirs`` and ``exempt_dirs``
    is a contradiction and MUST raise at config load time so the user
    fixes the config rather than getting silent surprising behavior.
  * ``find_python_files`` / ``find_catalog_files`` / ``iter_catalog_files``
    all consume the same resolved set — no two-list drift.
"""
from __future__ import annotations

from pathlib import Path

import pytest


class TestDefaultFileExcludePatterns:
    """Companion to DEFAULT_EXCLUDE_POLICY (dirs): the canonical default for
    vendored *files* that are never project source — pip/poetry bootstrap
    installers like ``get-pip.py``. Same no-drift contract as the dir policy:
    a single source in config.py, consumed by every discovery path.
    """

    def test_default_includes_vendored_installers(self) -> None:
        from config import DEFAULT_EXCLUDE_FILE_PATTERNS
        assert '**/get-pip.py' in DEFAULT_EXCLUDE_FILE_PATTERNS

    def test_find_catalog_files_excludes_get_pip_by_default(
        self, tmp_path: Path,
    ) -> None:
        from docgen.staleness import find_catalog_files
        (tmp_path / 'get-pip.py').write_text('# vendored pip installer\n')
        (tmp_path / 'real.py').write_text('def foo():\n    return 1\n')
        names = {p.name for p in find_catalog_files(tmp_path)}
        assert 'real.py' in names
        assert 'get-pip.py' not in names

    def test_find_python_files_excludes_get_pip_by_default(
        self, tmp_path: Path,
    ) -> None:
        from docgen.staleness import find_python_files
        (tmp_path / 'get-pip.py').write_text('# vendored pip installer\n')
        (tmp_path / 'real.py').write_text('def foo():\n    return 1\n')
        names = {p.name for p in find_python_files(tmp_path)}
        assert 'real.py' in names
        assert 'get-pip.py' not in names


