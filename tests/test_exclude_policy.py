def test_two_walk_paths_use_same_default_policy(tmp_path):
    """Regression guard: ``find_catalog_files`` and ``iter_catalog_files``
    must produce the same set of skipped directories for the same tree.

    Previously, ``staleness._EXCLUDED_DIRS`` and
    ``catalog_writer._SKIP_DIR_NAMES`` had drifted (e.g., ``.hg`` was in
    one but not the other; ``generated-docs`` only in the other). This
    test fails until both code paths consult the single canonical
    policy."""
    from docgen.catalog_writer import iter_catalog_files
    from docgen.staleness import find_catalog_files

    (tmp_path / 'src').mkdir()
    (tmp_path / 'src' / 'main.py').write_text('x = 1', encoding='utf-8')

    # Names historically in only ONE of the two private lists. After the
    # consolidation, both walks must skip both.
    for name in ('.hg', 'generated-docs', '.svn', '_site'):
        d = tmp_path / name
        d.mkdir()
        (d / 'leak.py').write_text('z = 3', encoding='utf-8')

    a = sorted(str(f.relative_to(tmp_path)) for f in find_catalog_files(tmp_path))
    b = sorted(str(f.relative_to(tmp_path)) for f in iter_catalog_files(tmp_path))

    assert a == b, (
        'find_catalog_files and iter_catalog_files diverged: '
        f'{set(a) ^ set(b)}'
    )
