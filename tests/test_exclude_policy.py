def test_find_catalog_files_default_excludes_policy_dirs(tmp_path):
    """When ``exclude_dir_names`` is not supplied, ``find_catalog_files``
    falls back to the canonical default policy — every name in the
    policy is pruned at every depth.

    ``target`` and ``.idea`` are deliberately NEW additions (absent
    from the legacy ``_EXCLUDED_DIRS``). If implementation still relies
    on the old hardcoded list, these will leak and the test will fail.
    """
    from config import DEFAULT_EXCLUDE_POLICY
    from docgen.staleness import find_catalog_files

    (tmp_path / 'src').mkdir()
    (tmp_path / 'src' / 'main.py').write_text('x = 1', encoding='utf-8')
    excluded_names = ('node_modules', '__pycache__', '.venv', 'target', '.idea')
    for excluded in excluded_names:
        d = tmp_path / excluded
        d.mkdir()
        (d / 'leaked.py').write_text('y = 2', encoding='utf-8')

    # Sanity: every name is in the default policy, otherwise this test
    # would silently pass for the wrong reason.
    for name in excluded_names:
        assert name in DEFAULT_EXCLUDE_POLICY, (
            f'{name} expected in DEFAULT_EXCLUDE_POLICY'
        )

    files = find_catalog_files(tmp_path)
    rels = sorted(str(f.relative_to(tmp_path)) for f in files)

    assert 'src/main.py' in rels
    for excluded in excluded_names:
        leaked = [r for r in rels if r.startswith(f'{excluded}/')]
        assert not leaked, (
            f'{excluded} subtree leaked: {leaked} '
            '(default policy not honored)'
        )


