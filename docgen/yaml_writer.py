"""Round-trip-safe ariadne.yaml mutation (Phase 2j.c).

When ``ariadne discover --review`` accepts a user's reject decision,
the suggested exclude pattern needs to land in ``ariadne.yaml`` under
``sources.<name>.exclude``. PyYAML can read+modify+write but loses
comments and reflows the file. Users would hate that.

ruamel.yaml's RoundTripLoader is purpose-built for this — it
preserves comments, line ordering, anchors, and formatting on
round-trip. Hence the new dependency.

This module exposes a single function (:func:`append_source_excludes`)
that adds patterns idempotently. Existing patterns are left in place
(no duplicates); new patterns are appended to the end of the source's
``exclude`` list.
"""
from __future__ import annotations

from pathlib import Path

from ruamel.yaml import YAML


def append_source_excludes(
    yaml_path: Path,
    source_name: str,
    new_patterns: list[str],
) -> int:
    """Append exclude patterns to a source's ``exclude:`` list.

    Returns the count of patterns ACTUALLY added (skipping any that
    were already present). On a no-op (empty input or all duplicates),
    the file is not rewritten.

    Raises:
        FileNotFoundError: if ``yaml_path`` does not exist.
        KeyError: if ``source_name`` is not in ``sources:``.
    """
    if not yaml_path.exists():
        raise FileNotFoundError(f'No yaml at {yaml_path}')
    if not new_patterns:
        return 0

    yaml = YAML()
    yaml.preserve_quotes = True
    # Match common ariadne.yaml indent style (2-space mapping, 2-space
    # sequence offset). ruamel preserves the original on round-trip
    # anyway; this is just defaults for new keys we create.
    yaml.indent(mapping=2, sequence=4, offset=2)

    # SAFETY: `yaml` here is a ruamel.yaml.YAML instance (round-trip
    # loader, typ='rt'), NOT the PyYAML module — so `yaml.load` below
    # does NOT honor `!!python/*` tags and cannot deserialize arbitrary
    # objects (verified: every classic PyYAML RCE payload loads as inert
    # data through this exact path). Static scanners that string-match
    # `yaml.load(` flag it as unsafe PyYAML; that is a false positive.
    # Defense in depth: the runtime config reader (config.py) uses
    # yaml.safe_load, which fails closed (ConstructorError) on such tags.
    with yaml_path.open('r', encoding='utf-8') as f:
        data = yaml.load(f)

    sources = data.get('sources') if data is not None else None
    if not sources or source_name not in sources:
        raise KeyError(
            f'Source {source_name!r} not found in {yaml_path}',
        )

    src = sources[source_name]
    existing = src.get('exclude') if src else None
    if existing is None:
        existing = []

    # Build the updated exclude list; track count of additions.
    added_count = 0
    updated = list(existing)
    for pattern in new_patterns:
        if pattern not in updated:
            updated.append(pattern)
            added_count += 1

    if added_count == 0:
        return 0

    src['exclude'] = updated

    with yaml_path.open('w', encoding='utf-8') as f:
        yaml.dump(data, f)

    return added_count


