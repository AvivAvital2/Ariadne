def write_source_scip_config(
    yaml_path: Path,
    source_name: str,
    *,
    catalog_scip_languages: set[str],
    artifact_path: Path | str,
    max_staleness_days: int = 7,
) -> bool:
    """Idempotently author the auto-managed ``index_kinds`` +
    ``scip:`` block for a source.

    Per the UX principle that ``ariadne.yaml`` should carry only
    user-authored fields (``path`` / ``depends_on`` / ``exclude`` /
    ``exclude_dirs``), this helper lets ``ariadne discover`` write
    every SCIP-related field that the rest of Ariadne needs.
    Subsequent ``discover`` runs are no-ops when the block already
    matches detection — the YAML stays stable across re-runs.

    ``catalog_scip_languages`` is the set of languages whose catalog
    extraction should route through SCIP (today: subset of
    ``{'scala', 'java', 'javascript'}`` — the languages
    ``catalog_extractor.extract_elements`` routes through
    ``scip_extractor`` when declared). Python is detected and indexed
    for cross-source data, but its catalog extraction stays on
    ast-grep because ast-grep's qualified_names already match what
    scip-python emits — no routing layer needed.

    Returns True if the file was rewritten, False if the content
    already matched the requested state.
    """
    if not yaml_path.exists():
        raise FileNotFoundError(f'No yaml at {yaml_path}')

    yaml = YAML()
    yaml.preserve_quotes = True
    yaml.indent(mapping=2, sequence=4, offset=2)

    # SAFETY: ruamel round-trip loader, not PyYAML — safe by default.
    # See the note in append_source_excludes above re: why `yaml.load`
    # here cannot execute arbitrary code (scanner false positive).
    with yaml_path.open('r', encoding='utf-8') as f:
        data = yaml.load(f)

    sources = data.get('sources') if data is not None else None
    if not sources or source_name not in sources:
        raise KeyError(
            f'Source {source_name!r} not found in {yaml_path}',
        )

    src = sources[source_name]
    if src is None:
        # ``sources.X:`` with nothing under it — shorthand for
        # ``sources.X: {path: ...}`` from a previous version. Coerce
        # to a real mapping so we have somewhere to write.
        src = {}
        sources[source_name] = src

    artifact_str = str(artifact_path)

    # Build expected state — sorted keys so re-runs are deterministic.
    expected_index_kinds = {
        lang: 'scip' for lang in sorted(catalog_scip_languages)
    }
    expected_scip = {
        'artifact_path': artifact_str,
        'max_staleness_days': max_staleness_days,
    }

    current_index_kinds = src.get('index_kinds') or {}
    current_scip = src.get('scip') or {}

    # Treat both as ordinary dicts for comparison (ruamel uses
    # CommentedMap, which compares equal to plain dict when keys
    # + values match).
    if (
        dict(current_index_kinds) == expected_index_kinds
        and dict(current_scip) == expected_scip
    ):
        return False

    src['index_kinds'] = expected_index_kinds
    src['scip'] = expected_scip

    with yaml_path.open('w', encoding='utf-8') as f:
        yaml.dump(data, f)

    return True


__all__ = ['append_source_excludes', 'write_source_scip_config']
