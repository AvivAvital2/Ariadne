#!/usr/bin/env node
'use strict';

/*
 * extract-vue-scripts.js — Vue SFC <script> extractor for scip-typescript.
 *
 * scip-typescript can't parse .vue Single File Components. This script
 * pulls the <script> / <script setup> blocks out of every .vue file under
 * the current working directory into a companion `<name>.vue.script.{js,ts}`
 * that scip-typescript CAN index, and records a vue-mapping.json so SCIP
 * positions can be translated back to the original .vue files.
 *
 * Invocation (by docgen/scip_indexers.py:_DefaultVueExtractor):
 *     node scripts/scip/extract-vue-scripts.js
 *   with cwd set to the typescript indexer's working directory and,
 *   optionally, ARIADNE_VUE_MAPPING_OUTPUT pointing at the mapping file.
 *
 * Line fidelity: companions are PADDED with blank lines so that every line
 * in the companion has the same line number as in the original .vue. The
 * mapping's line_offset is therefore always 0 — the loader only has to
 * translate the path, not shift line numbers. (See docgen/scip_cross_source
 * _apply_vue_mapping for the consumer.)
 *
 * Exit codes: 0 on success (including "no .vue files"); 1 on a missing
 * @vue/compiler-sfc, an I/O failure, or when every .vue file failed to
 * parse. Per-file parse errors are logged to stderr and skipped.
 */

const fs = require('fs');
const path = require('path');

const MARKER = 'AUTOGENERATED by Ariadne extract-vue-scripts';
const MARKER_LINE = `// ${MARKER} — DO NOT EDIT`;
const MARKER_INLINE = `/* ${MARKER} — DO NOT EDIT */ `;

const SKIP_DIRS = new Set([
  'node_modules', 'dist', '.git', '.ariadne', 'target', 'build',
]);
// Companion extensions we own — used by cleanup and the gitignore entry.
const COMPANION_RE = /\.vue\.script\.(js|ts|jsx|tsx)$/;
const GITIGNORE_PATTERN = '*.vue.script.*';

function loadCompilerSfc(cwd) {
  // Resolve from the consumed repo's node_modules — @vue/compiler-sfc is a
  // transitive dependency of `vue` itself, so any Vue project has it.
  try {
    const resolved = require.resolve('@vue/compiler-sfc', { paths: [cwd] });
    return require(resolved);
  } catch (err) {
    process.stderr.write(
      'Vue extractor: @vue/compiler-sfc not found. Install it in the ' +
      'project being indexed:\n  npm install --save-dev @vue/compiler-sfc\n',
    );
    return null;
  }
}

function walkVueFiles(root) {
  const out = [];
  const stack = [root];
  while (stack.length > 0) {
    const dir = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch (err) {
      continue; // unreadable dir — skip
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) stack.push(full);
      } else if (entry.isFile() && entry.name.endsWith('.vue')) {
        out.push(full);
      }
    }
  }
  return out;
}

// Delete companions we previously generated. The marker is the safety gate:
// a user file that merely matches *.vue.script.ts is left alone.
function cleanupStaleCompanions(root) {
  const stack = [root];
  while (stack.length > 0) {
    const dir = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch (err) {
      continue;
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) stack.push(full);
      } else if (entry.isFile() && COMPANION_RE.test(entry.name)) {
        let head = '';
        try {
          const fd = fs.openSync(full, 'r');
          const buf = Buffer.alloc(200);
          const n = fs.readSync(fd, buf, 0, 200, 0);
          fs.closeSync(fd);
          head = buf.toString('utf8', 0, n);
        } catch (err) {
          continue;
        }
        if (head.includes(MARKER)) {
          try { fs.unlinkSync(full); } catch (err) { /* best effort */ }
        }
      }
    }
  }
}

function extFor(lang) {
  switch ((lang || '').toLowerCase()) {
    case 'ts': return 'ts';
    case 'tsx': return 'tsx';
    case 'jsx': return 'jsx';
    default: return 'js';
  }
}

// Build the companion text. Each block's content is placed at its original
// 1-indexed start line, padding the gaps with blank lines so line numbers
// are preserved verbatim.
function buildCompanion(blocks) {
  const minStart = Math.min(...blocks.map((b) => b.startLine));
  const lines = [];
  if (minStart > 1) {
    lines[0] = MARKER_LINE; // marker gets its own line when there's room
  }
  for (const b of blocks) {
    const contentLines = b.content.split('\n');
    const base = b.startLine - 1; // 0-indexed
    for (let j = 0; j < contentLines.length; j++) {
      let text = contentLines[j];
      if (minStart === 1 && b.startLine === 1 && j === 0) {
        // No room for a standalone marker line — inline it so line 1 stays
        // line 1 (column accuracy is lost only for this rare case).
        text = MARKER_INLINE + text;
      }
      lines[base + j] = text;
    }
  }
  for (let i = 0; i < lines.length; i++) {
    if (lines[i] === undefined) lines[i] = '';
  }
  return lines.join('\n');
}

// Normalize across @vue/compiler-sfc major versions.
//
//   Vue 3:   parse(source, { filename })  ->  { descriptor, errors }
//   Vue 2.7: parse({ source, filename })  ->  SFCDescriptor  (errors live
//            on the descriptor; the positional-source form is silently
//            ignored, yielding a descriptor with no `.script`).
//
// Returns { descriptor, errors }. `descriptor` is null if neither calling
// convention produced one.
function parseSfc(sfc, source, filename) {
  // Try the Vue 3 convention first.
  let result;
  try {
    result = sfc.parse(source, { filename });
  } catch (err) {
    result = undefined;
  }
  if (result && result.descriptor) {
    return { descriptor: result.descriptor, errors: result.errors || [] };
  }
  // Vue 2.x: options-object form returns the descriptor directly.
  let descriptor;
  try {
    descriptor = sfc.parse({ source, filename });
  } catch (err) {
    return { descriptor: null, errors: [err] };
  }
  return {
    descriptor: descriptor || null,
    errors: (descriptor && descriptor.errors) || [],
  };
}

// 1-indexed line of a block's first content character.
//
//   Vue 3:   block.loc.start.line is provided directly.
//   Vue 2.7: only a character offset (block.start) is provided, so derive
//            the line by counting newlines up to that offset — which equals
//            what Vue 3 reports.
function startLineOf(block, source) {
  if (block.loc && block.loc.start && typeof block.loc.start.line === 'number') {
    return block.loc.start.line;
  }
  if (typeof block.start === 'number') {
    return source.slice(0, block.start).split('\n').length;
  }
  return 1; // last-resort fallback — keeps the block at the top of the file
}

function relPosix(root, file) {
  return path.relative(root, file).split(path.sep).join('/');
}

function ensureGitignore(root) {
  const gitignorePath = path.join(root, '.gitignore');
  let existing = '';
  try {
    existing = fs.readFileSync(gitignorePath, 'utf8');
  } catch (err) {
    existing = '';
  }
  const hasPattern = existing
    .split('\n')
    .some((line) => line.trim() === GITIGNORE_PATTERN);
  if (hasPattern) return;
  const prefix = existing.length > 0 && !existing.endsWith('\n') ? '\n' : '';
  const block =
    `${prefix}# Ariadne Vue extractor companions (generated, transient)\n` +
    `${GITIGNORE_PATTERN}\n`;
  try {
    fs.appendFileSync(gitignorePath, block);
  } catch (err) {
    // Non-fatal: failing to write .gitignore shouldn't break indexing.
    process.stderr.write(
      `Vue extractor: could not update ${gitignorePath}: ${err.message}\n`,
    );
  }
}

function main() {
  const cwd = process.cwd();
  const vueFiles = walkVueFiles(cwd);
  if (vueFiles.length === 0) {
    return 0; // nothing to do — silent success
  }

  const sfc = loadCompilerSfc(cwd);
  if (sfc === null) {
    return 1;
  }

  cleanupStaleCompanions(cwd);

  const mapping = {};
  let anyWritten = false;
  let anyFailed = false;

  for (const vueFile of vueFiles) {
    let source;
    try {
      source = fs.readFileSync(vueFile, 'utf8');
    } catch (err) {
      process.stderr.write(
        `Vue extractor: cannot read ${vueFile}: ${err.message}\n`,
      );
      anyFailed = true;
      continue;
    }

    let descriptor;
    let errors;
    try {
      ({ descriptor, errors } = parseSfc(sfc, source, vueFile));
    } catch (err) {
      process.stderr.write(
        `Vue extractor: parse error in ${relPosix(cwd, vueFile)}: ` +
        `${err.message}\n`,
      );
      anyFailed = true;
      continue;
    }
    if (errors && errors.length > 0) {
      process.stderr.write(
        `Vue extractor: parse error in ${relPosix(cwd, vueFile)}: ` +
        `${errors[0].message || errors[0]}\n`,
      );
      anyFailed = true;
      continue;
    }
    // A successful parse can still yield no descriptor (e.g. an
    // unsupported compiler-sfc shape). Skip + log rather than crashing
    // the whole index on `descriptor.script` below.
    if (!descriptor) {
      process.stderr.write(
        `Vue extractor: no descriptor for ${relPosix(cwd, vueFile)} ` +
        `(unsupported @vue/compiler-sfc?) — skipping\n`,
      );
      anyFailed = true;
      continue;
    }

    // Collect script blocks, skipping external (src=) references — those
    // point at standalone files scip-typescript already indexes directly.
    const rawBlocks = [];
    if (descriptor.script && !descriptor.script.attrs.src) {
      rawBlocks.push({ block: descriptor.script, setup: false });
    }
    if (descriptor.scriptSetup && !descriptor.scriptSetup.attrs.src) {
      rawBlocks.push({ block: descriptor.scriptSetup, setup: true });
    }
    if (rawBlocks.length === 0) {
      continue; // template/style-only SFC — nothing to index
    }

    // Prefer <script setup>'s lang when present (Vue 3 convention).
    const setupBlock = rawBlocks.find((b) => b.setup);
    const plainBlock = rawBlocks.find((b) => !b.setup);
    const lang =
      (setupBlock && setupBlock.block.attrs.lang) ||
      (plainBlock && plainBlock.block.attrs.lang) ||
      'js';
    const ext = extFor(lang);

    const blocks = rawBlocks.map(({ block }) => ({
      content: block.content,
      startLine: startLineOf(block, source), // 1-indexed line of first content char
    }));

    let companionText;
    try {
      companionText = buildCompanion(blocks);
    } catch (err) {
      process.stderr.write(
        `Vue extractor: failed to build companion for ` +
        `${relPosix(cwd, vueFile)}: ${err.message}\n`,
      );
      anyFailed = true;
      continue;
    }

    const companionPath = `${vueFile}.script.${ext}`;
    try {
      fs.writeFileSync(companionPath, companionText, 'utf8');
    } catch (err) {
      process.stderr.write(
        `Vue extractor: cannot write ${companionPath}: ${err.message}\n`,
      );
      anyFailed = true;
      continue;
    }

    let blockType = 'script';
    if (setupBlock && plainBlock) blockType = 'script+setup';
    else if (setupBlock) blockType = 'script-setup';

    mapping[relPosix(cwd, companionPath)] = {
      original: relPosix(cwd, vueFile),
      line_offset: 0,
      block_type: blockType,
    };
    anyWritten = true;
  }

  if (!anyWritten && anyFailed) {
    process.stderr.write('Vue extractor: all .vue files failed to parse\n');
    return 1;
  }

  const outputPath =
    process.env.ARIADNE_VUE_MAPPING_OUTPUT ||
    path.join(cwd, '.ariadne', 'intermediate', 'vue-mapping.json');
  try {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, JSON.stringify(mapping, null, 2), 'utf8');
  } catch (err) {
    process.stderr.write(
      `Vue extractor: cannot write mapping ${outputPath}: ${err.message}\n`,
    );
    return 1;
  }

  ensureGitignore(cwd);
  return 0;
}

// Run as a script; stay requireable from tests (which exercise the
// version-normalization helpers without a real @vue/compiler-sfc).
if (require.main === module) {
  process.exit(main());
}

module.exports = { parseSfc, startLineOf, buildCompanion, extFor };
